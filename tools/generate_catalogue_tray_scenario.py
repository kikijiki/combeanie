"""Emit the scenario that stocks every generated catalogue product on the stock tray.

Run tools/label_factory.py first. The products stand upright and pinned in rows of six, each
carrying its own label texture on a white base (an albedo map is multiplied by the material colour,
so any tint would corrupt the artwork). It is the identity and stock-counting testbed: look-alike
pairs sit side by side, so a camera has to read the label.

    python3 tools/generate_catalogue_tray_scenario.py          # rewrite
    python3 tools/generate_catalogue_tray_scenario.py --check  # fail if it would change
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ros_ws" / "src" / "restocker_gazebo"))
sys.path.insert(0, str(ROOT / "tools"))

import label_factory  # noqa: E402
from restocker_gazebo.lane_columns import BOX_CATALOGUE, CATALOGUE  # noqa: E402
from restocker_gazebo.tray_arrangements import (  # noqa: E402
    TRAY_CENTRE_X_M,
    TRAY_CENTRE_Y_M,
    TRAY_SURFACE_Z_M,
    tray_scenario,
)

OUT = ROOT / "ros_ws" / "src" / "restocker_gazebo" / "config" / "generated_catalogue_products.yaml"
COLUMNS = 7
COLUMN_PITCH_M = 0.19
ROW_OFFSETS_M = (-0.19, 0.0, 0.19)
CLASS_KEYS = {
    "can": "can.standard",
    "small_bottle": "bottle.small.standard",
    "large_bottle": "bottle.large.standard",
}
# Contoured bottles have no lane_columns entry; they are perception-only, so only mass, friction
# and height matter here.
CONTOUR_DEFAULTS = {
    "mass_kg": 0.75,
    "friction": 0.72,
    "height_m": label_factory.SHAPES["contour_bottle"]["height"],
}
HEADER = """# Generated by tools/generate_catalogue_tray_scenario.py. Do not hand-edit.
# Copyright 2026 Matteo Bernacchia <dev@kikijiki.com>
#
# Every generated catalogue product (tools/label_factory.py) pinned upright on the stock tray,
# three rows of seven: cans and bottles, four contoured bottles, then the four boxes (turned half
# a turn so their front faces the tray camera at +y). Look-alike pairs are neighbours: same layout
# and palette, a different flavour word.
"""


def build() -> dict:
    products = []
    for index, spec in enumerate(label_factory.build_catalogue()):
        row, column = divmod(index, COLUMNS)
        x = TRAY_CENTRE_X_M + (column - (COLUMNS - 1) / 2) * COLUMN_PITCH_M
        y = TRAY_CENTRE_Y_M + ROW_OFFSETS_M[row]
        if spec.is_box:
            box = BOX_CATALOGUE[f"box.{spec.variant}"]
            defaults = {**box, "height_m": box["size_xyz_m"][2]}
        elif spec.shape == "contour_bottle":
            defaults = CONTOUR_DEFAULTS
        else:
            defaults = CATALOGUE[CLASS_KEYS[spec.shape]]
        name = f"tray_{spec.sku.lower().replace('-', '_')}"
        products.append(
            {
                "model_name": name,
                "source_object_id": f"sim:{name}",
                "geometry_key": spec.geometry_key,
                "product_class": spec.shape,
                "sku": spec.sku,
                "mass_kg": defaults["mass_kg"],
                "rgba": [1.0, 1.0, 1.0, 1.0],
                "label_texture": spec.texture,
                "friction": defaults["friction"],
                "spawn_pose": upright_pose_for(
                    x, y, defaults["height_m"], math.pi if spec.is_box else 0.0
                ),
                "static": True,
            }
        )
        if spec.is_box:
            mesh = label_factory.box_mesh_name(spec.variant)
        else:
            mesh = label_factory.SHAPES[spec.shape].get("visual_mesh")
        if mesh:
            products[-1]["visual_mesh"] = mesh
    return tray_scenario(products)


def upright_pose_for(x: float, y: float, height_m: float, yaw: float = 0.0) -> list[float]:
    z = round(TRAY_SURFACE_Z_M + height_m / 2.0, 6)
    return [round(x, 6), round(y, 6), z, 0.0, 0.0, round(yaw, 6)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = HEADER + yaml.safe_dump(build(), sort_keys=False, default_flow_style=False)
    if args.check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

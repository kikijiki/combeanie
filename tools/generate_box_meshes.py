"""Emit one visual box mesh per box variant, with per-face UVs into the label atlas.

The mesh is visual only, like the contour bottle: the collision is the catalogue box. Each of the
six faces has its own four vertices (hard edges) and UVs that index the face's rectangle in the
atlas tools/label_factory.py draws, so every face shows its panel upright and unmirrored seen from
outside. The mesh is centred on the origin in the product frame (x width, y depth, z height; the
front face looks along -y). The layout comes from label_factory.box_layout, so the mesh and the
atlas cannot drift apart.

    python3 tools/generate_box_meshes.py          # rewrite
    python3 tools/generate_box_meshes.py --check  # fail if it would change
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import label_factory  # noqa: E402

MESH_DIR = ROOT / "ros_ws" / "src" / "restocker_gazebo" / "meshes"


def build_obj(variant: str) -> str:
    size = label_factory.BOX_VARIANTS[variant]["size"]
    layout = label_factory.box_layout(size)
    atlas_w, atlas_h = layout["atlas"]
    lines = [
        "# Generated by tools/generate_box_meshes.py. Do not hand-edit.",
        f"o {variant}",
    ]
    verts, uvs, normals, faces = [], [], [], []
    for name in label_factory.BOX_FACES:
        normal, right, up = label_factory.BOX_FACE_FRAMES[name]
        x, y, w, h = layout["rects"][name]
        extent = lambda axis: sum(abs(a) * s for a, s in zip(axis, size, strict=True))  # noqa: E731
        half_n, span_r, span_u = extent(normal) / 2, extent(right), extent(up)
        base = len(verts)
        for a, b in ((0, 0), (1, 0), (1, 1), (0, 1)):
            verts.append(
                tuple(
                    normal[i] * half_n + (a - 0.5) * span_r * right[i] + (b - 0.5) * span_u * up[i]
                    for i in range(3)
                )
            )
            uvs.append(((x + a * w) / atlas_w, 1.0 - (y + (1 - b) * h) / atlas_h))
            normals.append(normal)
        faces.append((base + 1, base + 2, base + 3, base + 4))
    lines += [f"v {a:.6f} {b:.6f} {c:.6f}" for a, b, c in verts]
    lines += [f"vt {u:.6f} {v:.6f}" for u, v in uvs]
    lines += [f"vn {a:.1f} {b:.1f} {c:.1f}" for a, b, c in normals]
    for p, q, r, s in faces:
        lines.append(f"f {p}/{p}/{p} {q}/{q}/{q} {r}/{r}/{r}")
        lines.append(f"f {p}/{p}/{p} {r}/{r}/{r} {s}/{s}/{s}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = 0
    for variant in label_factory.BOX_VARIANTS:
        path = MESH_DIR / label_factory.box_mesh_name(variant)
        text = build_obj(variant)
        if path.exists() and path.read_text() == text:
            continue
        stale += 1
        if not args.check:
            MESH_DIR.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())

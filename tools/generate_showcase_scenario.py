"""Emit the showcase scenario and lane policy used by `just demo showcase:=true`.

Usage::

    tools/generate_showcase_scenario.py          # write both documents
    tools/generate_showcase_scenario.py --check  # exit 1 if either is stale
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPOSITORY_ROOT / "ros_ws" / "src" / "restocker_gazebo"))

from restocker_gazebo import showcase  # noqa: E402

GAZEBO_CONFIG = REPOSITORY_ROOT / "ros_ws" / "src" / "restocker_gazebo" / "config"
SCENARIO_OUT = GAZEBO_CONFIG / "showcase_products.yaml"
LANES_OUT = (
    REPOSITORY_ROOT / "ros_ws" / "src" / "restocker_world_state" / "config" / "showcase_lanes.yaml"
)
LABELS = GAZEBO_CONFIG / "generated_product_labels.yaml"

SCENARIO_HEADER = """# Generated by tools/generate_showcase_scenario.py. Do not hand-edit.
# Copyright 2026 Matteo Bernacchia <dev@kikijiki.com>
#
# A stocked shelf and a packed back room of the generated, labelled catalogue products
# (tools/label_factory.py): cans, small bottles and large bottles, two SKUs of each shape except
# the large bottle, which holds two lanes.
#
# SHELF (+Y), pinned: {shelf}.
# BACK ROOM (-Y), one two-column block per SKU, left to right: {back}.
# Under showcase_lanes.yaml the shelf is short {short} of its targets; the back room covers those
# deficits and keeps the rest of each block, and the blocks of SKUs with no deficit, as reserve.
#
# Block columns stand on the approach-corridor pitch and rows touch to within a few millimetres
# (restocker_gazebo/showcase.py carries the arithmetic).
"""

LANES_HEADER = """# Generated by tools/generate_showcase_scenario.py. Do not hand-edit.
# Copyright 2026 Matteo Bernacchia <dev@kikijiki.com>
#
# Lane policy for restocker_gazebo/config/showcase_products.yaml. Each lane names one generated
# SKU; the large bottle holds lanes 3 and 6. Targets are the dense fixture's measured regime: short
# of surveyed capacity, so every placement is a clean insertion at the rear mouth.
#
# Pair this file with the showcase scenario only. The demo disables lane_policy_state persistence
# so a stale SetLanePolicy document cannot overlay these targets.
"""


def render() -> dict[Path, str]:
    """Return the text of every generated document, keyed by its path."""
    labels = yaml.safe_load(LABELS.read_text())
    scenario = showcase.showcase_scenario(labels)
    short = showcase.deficits(labels)
    header = SCENARIO_HEADER.format(
        shelf=", ".join(f"{lane} {count} {sku}" for lane, sku, count in showcase.SHELF),
        back=", ".join(f"{count} {sku}" for sku, count in showcase.BACK_ROOM),
        short=", ".join(f"{count} {sku}" for sku, count in short.items() if count),
    )
    dump = {"sort_keys": False, "default_flow_style": False}
    return {
        SCENARIO_OUT: header + yaml.safe_dump(scenario, **dump),
        LANES_OUT: LANES_HEADER + yaml.safe_dump(showcase.lane_policy(labels), **dump),
    }


def main(argv: list[str] | None = None) -> int:
    """Write the showcase documents, or with --check report whether they are current."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    documents = render()
    if arguments.check:
        stale = [
            path
            for path, text in documents.items()
            if not path.exists() or path.read_text() != text
        ]
        for path in stale:
            print(f"stale: {path.relative_to(REPOSITORY_ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in documents.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(REPOSITORY_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

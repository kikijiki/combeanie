"""Emit the contoured plastic-bottle visual mesh: a surface of revolution with a waist and ribs.

The mesh is visual only. The collision stays the catalogue cylinder (the bottle's maximum radius),
so physics, grasp planning and every catalogue loader see an ordinary cylinder. UVs are u = angle
once around, v = height, so the same unwrapped label strip that tools/label_factory.py draws for a
cylinder wraps the bottle. The mesh is centred on the origin with its axis along z, like the
URDF cylinder it replaces.

    python3 tools/generate_bottle_meshes.py          # rewrite
    python3 tools/generate_bottle_meshes.py --check  # fail if it would change
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
MESH_DIR = ROOT / "ros_ws" / "src" / "restocker_gazebo" / "meshes"

SEGMENTS = 96
# Height stations (m above the bottle's base) and radius (m): petaloid-ish heel, straight lower
# body, a pinched waist with a grip rib either side, a shoulder taper, a neck with a cap ring.
CONTOUR_BOTTLE = {
    "name": "contour_bottle.obj",
    "height": 0.230,
    "profile": (
        (0.000, 0.000),
        (0.000, 0.022),
        (0.003, 0.029),
        (0.010, 0.034),
        (0.020, 0.036),
        (0.050, 0.036),
        (0.066, 0.0345),
        (0.080, 0.0315),
        (0.098, 0.0300),
        (0.114, 0.0315),
        (0.128, 0.0345),
        (0.140, 0.036),
        (0.160, 0.036),
        (0.172, 0.0345),
        (0.186, 0.0290),
        (0.198, 0.0215),
        (0.206, 0.0160),
        (0.212, 0.0140),
        (0.220, 0.0140),
        (0.2205, 0.0155),
        (0.2255, 0.0155),
        (0.2260, 0.0140),
        (0.2300, 0.0140),
        (0.2300, 0.000),
    ),
}


def _smooth(
    profile: tuple[tuple[float, float], ...], per_span: int = 4
) -> list[tuple[float, float]]:
    """Catmull-Rom through the stations so the surface has no visible facets."""
    pts = list(profile)
    out: list[tuple[float, float]] = []
    for i in range(len(pts) - 1):
        p0 = pts[max(i - 1, 0)]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[min(i + 2, len(pts) - 1)]
        for k in range(per_span):
            t = k / per_span
            t2, t3 = t * t, t * t * t
            out.append(
                tuple(
                    0.5
                    * (
                        2 * p1[j]
                        + (-p0[j] + p2[j]) * t
                        + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                        + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3
                    )
                    for j in (0, 1)
                )
            )
    out.append(pts[-1])
    # The profile is (z, r) per station; keep it as (z, r).
    top = max(z for z, _ in pts)
    return [(min(max(z, 0.0), top), max(r, 0.0)) for z, r in out]


def build_obj(spec: dict) -> str:
    height = spec["height"]
    rings = _smooth(tuple(spec["profile"]))
    lines = [
        "# Generated by tools/generate_bottle_meshes.py. Do not hand-edit.",
        "o contour_bottle",
    ]
    verts, uvs, normals = [], [], []
    columns = SEGMENTS + 1
    for z, r in rings:
        for s in range(columns):
            a = 2 * math.pi * s / SEGMENTS
            verts.append((r * math.cos(a), r * math.sin(a), z - height / 2))
            uvs.append((s / SEGMENTS, z / height))
    # Normals from the ring-to-ring slope; flat caps get the axis.
    for i in range(len(rings)):
        z_prev, r_prev = rings[max(i - 1, 0)]
        z_next, r_next = rings[min(i + 1, len(rings) - 1)]
        dz, dr = z_next - z_prev, r_next - r_prev
        length = math.hypot(dz, dr) or 1.0
        nr, nz = dz / length, -dr / length
        for s in range(columns):
            a = 2 * math.pi * s / SEGMENTS
            normals.append((nr * math.cos(a), nr * math.sin(a), nz))
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in verts]
    lines += [f"vt {u:.6f} {v:.6f}" for u, v in uvs]
    lines += [f"vn {x:.5f} {y:.5f} {z:.5f}" for x, y, z in normals]
    for i in range(len(rings) - 1):
        for s in range(SEGMENTS):
            a = i * columns + s + 1
            b = a + 1
            c = a + columns
            d = c + 1
            lines.append(f"f {a}/{a}/{a} {b}/{b}/{b} {d}/{d}/{d}")
            lines.append(f"f {a}/{a}/{a} {d}/{d}/{d} {c}/{c}/{c}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    path = MESH_DIR / CONTOUR_BOTTLE["name"]
    text = build_obj(CONTOUR_BOTTLE)
    if args.check:
        return 0 if path.exists() and path.read_text() == text else 1
    MESH_DIR.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
